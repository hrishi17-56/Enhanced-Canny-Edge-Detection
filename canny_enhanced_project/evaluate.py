"""Run all experiments and write CSV tables, figures and results/summary.md.

    python evaluate.py                 # full run (a few minutes on a laptop)
    python evaluate.py --quick         # small smoke test
    python evaluate.py --extra-images my_photos/   # also test your own images

Experiments
  E1  per-stage time and peak memory of the improved pipeline on every image
  E2  speed against image resolution for all methods (original only on small images)
  E3  accuracy (precision, recall, F1) on drawn scenes with known edges, against noise level
  E4  the same against contrast and brightness changes
  E5  real photographs: agreement with OpenCV Canny and edge density (no ground truth)
Nothing here is hard-coded. Every number in the output comes from this run.
"""
import argparse
import glob
import os
import platform
import time

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import PIL.Image  # noqa: E402
import scipy  # noqa: E402

from canny_improved import baselines as B  # noqa: E402
from canny_improved import canny_improved  # noqa: E402
from canny_improved.metrics import agreement_f1, edge_density, edge_prf  # noqa: E402
from canny_improved.profiling import peak_memory_mb, time_call  # noqa: E402
from canny_improved.stages import to_gray  # noqa: E402
from canny_improved.synthetic import (add_noise, change_brightness, change_contrast, resize,  # noqa: E402
                                      synthetic_scene)
from canny_improved.thresholds import select_thresholds  # noqa: E402
from canny_improved.visualize import comparison_grid, stage_grid  # noqa: E402

ROOT = os.path.dirname(os.path.abspath(__file__))
DENOISERS = ["gaussian", "median", "bilateral", "nlm"]
THRESHOLDS = ["fixed", "median", "otsu"]


def methods_for_accuracy(include_script):
    """name -> function(gray float array) -> uint8 edge map."""
    m = {}
    m["manual_original_style"] = lambda g: canny_improved(g, kernel="original", nms_ties="suppress_all", quantize="trunc").edges
    for d in DENOISERS:
        for t in THRESHOLDS:
            m[f"improved_{d}_{t}"] = (lambda g, d=d, t=t: canny_improved(g, denoise=d, threshold=t).edges)
    m["opencv_fixed"] = lambda g: B.opencv_canny(g, 20, 40)
    m["opencv_median"] = lambda g: B.opencv_canny(g, *select_thresholds("median", g, g))
    m["sobel"] = B.sobel_edges
    m["prewitt"] = B.prewitt_edges
    m["laplacian"] = B.laplacian_edges
    if include_script:
        m["original_script"] = lambda g: B.original_manual_canny(g, 1, 20, 40)
    return m


def md_table(rows, cols, fmt=None):
    fmt = fmt or {}
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in rows:
        out.append("| " + " | ".join(fmt.get(c, str)(r[c]) if c in r else "" for c in cols) + " |")
    return "\n".join(out)


def write_csv(path, rows):
    import csv

    if not rows:
        return
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)


def load_images(extra):
    paths = sorted(glob.glob(os.path.join(ROOT, "images", "*")))
    if extra:
        paths += sorted(p for p in glob.glob(os.path.join(extra, "*")) if p.lower().endswith((".png", ".jpg", ".jpeg", ".bmp")))
    out = []
    for p in paths:
        if p.lower().endswith((".png", ".jpg", ".jpeg", ".bmp")):
            im = PIL.Image.open(p)
            out.append((os.path.basename(p), p, im.mode, im.size))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--outdir", default=os.path.join(ROOT, "results"))
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--scenes", type=int, default=5)
    ap.add_argument("--scene-size", type=int, default=128)
    ap.add_argument("--repeats", type=int, default=3)
    ap.add_argument("--original-max", type=int, default=256, help="largest image side the slow original script is timed on")
    ap.add_argument("--extra-images", default=None)
    args = ap.parse_args()
    if args.quick:
        args.scenes, args.repeats, args.scene_size = 2, 1, 96
    fig_dir = os.path.join(args.outdir, "figures")
    os.makedirs(fig_dir, exist_ok=True)
    t_start = time.time()
    md = ["# Evaluation results", "",
          f"Generated by evaluate.py on {time.strftime('%Y-%m-%d %H:%M')}. Python {platform.python_version()}, "
          f"NumPy {np.__version__}, SciPy {scipy.__version__}, {platform.platform()}, {os.cpu_count()} logical CPUs. "
          f"Settings: {args.scenes} scenes of {args.scene_size} px, {args.repeats} timing repeats. "
          "Timings depend on the machine, so rerun this script on your own computer before quoting them.", ""]
    images = load_images(args.extra_images)

    # ---------------- E1: per-stage profile ----------------
    e1 = []
    for name, path, mode, size in images:
        rgb = np.asarray(PIL.Image.open(path).convert("RGB" if mode != "L" else "L"))
        canny_improved(rgb)                                      # warm-up
        runs = [canny_improved(rgb).timings for _ in range(max(args.repeats, 3))]
        med = {k: float(np.median([r[k] for r in runs])) for k in runs[0]}
        e1.append({"image": name, "size": f"{size[0]}x{size[1]}", "mode": mode, **{k: round(v, 3) for k, v in med.items()},
                   "peak_mem_mb": round(peak_memory_mb(lambda: canny_improved(rgb)), 1)})
    write_csv(os.path.join(args.outdir, "e1_stage_profile.csv"), e1)
    md += ["## E1. Time per stage of the improved pipeline (ms, median)", "",
           md_table(e1, ["image", "size", "grayscale", "smoothing", "sobel", "magnitude", "nms", "thresholds",
                         "double_threshold", "hysteresis", "total", "peak_mem_mb"]), "",
           "Peak memory is the NumPy allocation peak seen by tracemalloc. It excludes memory used inside OpenCV and the interpreter itself.", ""]

    # ---------------- E2: speed vs resolution ----------------
    base = to_gray(os.path.join(ROOT, "images", "Lenna.png"))
    sizes = [128, 256] if args.quick else [128, 256, 512, 1024]
    e2 = []
    for s in sizes:
        g = resize(base, s)
        rgb = np.clip(g, 0, 255).astype(np.uint8)
        row = {"size": f"{s}x{s}"}
        fns = {"improved": lambda: canny_improved(g), "opencv_canny": lambda: B.opencv_canny(g),
               "sobel": lambda: B.sobel_edges(g), "prewitt": lambda: B.prewitt_edges(g), "laplacian": lambda: B.laplacian_edges(g)}
        if s <= args.original_max:
            fns["original_script"] = lambda: B.original_manual_canny(rgb)
        for n, fn in fns.items():
            row[n + "_ms"] = round(time_call(fn, args.repeats if n != "original_script" else 1, 1 if n != "original_script" else 0)[0], 2)
        row["improved_mem_mb"] = round(peak_memory_mb(lambda: canny_improved(g)), 1)
        if "original_script" in fns:
            row["original_mem_mb"] = round(peak_memory_mb(lambda: B.original_manual_canny(rgb)), 1)
            row["speedup_vs_original"] = round(row["original_script_ms"] / row["improved_ms"], 1)
        e2.append(row)
    write_csv(os.path.join(args.outdir, "e2_speed_resolution.csv"), e2)
    cols2 = ["size", "original_script_ms", "improved_ms", "speedup_vs_original", "opencv_canny_ms", "sobel_ms", "prewitt_ms",
             "laplacian_ms", "improved_mem_mb", "original_mem_mb"]
    md += ["## E2. Run time against image resolution (ms, median)", "", md_table(e2, cols2), "",
           f"The original script is timed once per size and only up to {args.original_max} px because it is slow. "
           "Blank cells mean it was not run. OpenCV runs compiled C++ code, so it is expected to be faster than any NumPy version.", ""]
    fig, ax = plt.subplots(figsize=(6, 4))
    xs = [int(r["size"].split("x")[0]) for r in e2]
    for n in ["improved", "opencv_canny", "sobel", "prewitt", "laplacian"]:
        ax.plot(xs, [r[n + "_ms"] for r in e2], marker="o", label=n)
    xo = [int(r["size"].split("x")[0]) for r in e2 if "original_script_ms" in r]
    ax.plot(xo, [r["original_script_ms"] for r in e2 if "original_script_ms" in r], marker="s", color="k", label="original_script")
    ax.set_xscale("log", base=2); ax.set_yscale("log"); ax.set_xlabel("image side (px)"); ax.set_ylabel("time (ms)")
    ax.legend(fontsize=8); ax.grid(alpha=.3); fig.tight_layout(); fig.savefig(os.path.join(fig_dir, "speed_vs_resolution.png"), dpi=120); plt.close(fig)

    # ---------------- E3: accuracy against noise ----------------
    meths = methods_for_accuracy(include_script=True)
    noises = [0, 20] if args.quick else [0, 10, 20, 30]
    scenes = [synthetic_scene(args.scene_size, s) for s in range(args.scenes)]
    e3 = []
    for sig in noises:
        for name, fn in meths.items():
            sc = [edge_prf(fn(add_noise(img, sig, seed)), gt) for seed, (img, gt) in enumerate(scenes)]
            e3.append({"noise_sigma": sig, "method": name, **{k: round(float(np.mean([r[k] for r in sc])), 3) for k in ("precision", "recall", "f1")},
                       "f1_std": round(float(np.std([r["f1"] for r in sc])), 3)})
    write_csv(os.path.join(args.outdir, "e3_accuracy_noise.csv"), e3)
    pivot = {}
    for r in e3:
        pivot.setdefault(r["method"], {"method": r["method"]})[f"noise {r['noise_sigma']}"] = r["f1"]
    md += ["## E3. F1 score on drawn scenes with known edges, against noise", "",
           f"Mean F1 over {args.scenes} scenes, tolerance 2 px. Noise is Gaussian, sigma in grey levels (0 to 255 scale). "
           "Precision, recall and standard deviation are in e3_accuracy_noise.csv.", "",
           md_table(list(pivot.values()), ["method"] + [f"noise {s}" for s in noises]), ""]
    fig, ax = plt.subplots(figsize=(7, 4.5))
    for n in ["manual_original_style", "improved_gaussian_fixed", "improved_gaussian_median", "improved_gaussian_otsu",
              "improved_bilateral_otsu", "improved_nlm_otsu", "opencv_fixed", "opencv_median", "sobel", "original_script"]:
        ax.plot(noises, [pivot[n][f"noise {s}"] for s in noises], marker="o", label=n)
    ax.set_xlabel("noise sigma"); ax.set_ylabel("mean F1"); ax.set_ylim(0, 1.02); ax.grid(alpha=.3); ax.legend(fontsize=7)
    fig.tight_layout(); fig.savefig(os.path.join(fig_dir, "f1_vs_noise.png"), dpi=120); plt.close(fig)

    # ---------------- E4: contrast and brightness ----------------
    cond = [("contrast x0.25", lambda a: change_contrast(a, .25)), ("contrast x0.5", lambda a: change_contrast(a, .5)),
            ("normal", lambda a: a.astype(float)), ("contrast x1.5", lambda a: change_contrast(a, 1.5)),
            ("dark (gamma 2)", lambda a: change_brightness(a, 2.0)), ("bright (gamma 0.5)", lambda a: change_brightness(a, .5))]
    if args.quick:
        cond = cond[:3]
    pick = ["manual_original_style", "improved_gaussian_fixed", "improved_gaussian_median", "improved_gaussian_otsu", "opencv_fixed",
            "opencv_median", "sobel", "original_script"]
    e4 = []
    for cname, tf in cond:
        for name in pick:
            sc = [edge_prf(meths[name](add_noise(tf(img), 5, seed)), gt) for seed, (img, gt) in enumerate(scenes)]
            e4.append({"condition": cname, "method": name, "f1": round(float(np.mean([r["f1"] for r in sc])), 3),
                       "precision": round(float(np.mean([r["precision"] for r in sc])), 3), "recall": round(float(np.mean([r["recall"] for r in sc])), 3)})
    write_csv(os.path.join(args.outdir, "e4_conditions.csv"), e4)
    piv4 = {}
    for r in e4:
        piv4.setdefault(r["method"], {"method": r["method"]})[r["condition"]] = r["f1"]
    md += ["## E4. F1 score against contrast and brightness changes", "",
           "Same scenes with light noise (sigma 5) added after the change. Fixed thresholds (20 and 40) are not rescaled for the new contrast.", "",
           md_table(list(piv4.values()), ["method"] + [c for c, _ in cond]), ""]

    # ---------------- E5: real photographs ----------------
    e5 = []
    for name, path, mode, size in images:
        rgb = np.asarray(PIL.Image.open(path).convert("RGB" if mode != "L" else "L"))
        g = to_gray(rgb)
        if max(g.shape) > 512:
            s = 512 / max(g.shape)
            rgb = np.asarray(PIL.Image.fromarray(rgb).resize((round(g.shape[1] * s), round(g.shape[0] * s))))
            g = to_gray(rgb)
        ref = B.opencv_canny(g, *select_thresholds("median", g, g))
        outs = {"improved_fixed": canny_improved(rgb).edges, "improved_median": canny_improved(rgb, threshold="median").edges,
                "improved_otsu": canny_improved(rgb, threshold="otsu").edges, "sobel": B.sobel_edges(g),
                "prewitt": B.prewitt_edges(g), "laplacian": B.laplacian_edges(g)}
        row = {"image": name, "opencv_density_%": round(100 * edge_density(ref), 2)}
        for n, e in outs.items():
            row[n + "_agree"] = round(agreement_f1(e, ref), 3)
            row[n + "_density_%"] = round(100 * edge_density(e), 2)
        e5.append(row)
        if name in ("Lenna.png", "bird 2.jpg", "house.jpg"):
            comparison_grid(rgb, {"Improved (fixed)": outs["improved_fixed"], "Improved (median thr)": outs["improved_median"],
                                  "Improved (Otsu thr)": outs["improved_otsu"], "OpenCV Canny": ref, "Sobel": outs["sobel"],
                                  "Prewitt": outs["prewitt"], "Laplacian": outs["laplacian"]},
                            os.path.join(fig_dir, f"comparison_{os.path.splitext(name)[0].replace(' ', '_')}.png"), title=name)
            plt.close("all")
            res = canny_improved(rgb, threshold="median", keep_stages=True)
            stage_grid(rgb, res, os.path.join(fig_dir, f"stages_{os.path.splitext(name)[0].replace(' ', '_')}.png"), title=f"{name}: median threshold")
            plt.close("all")
    write_csv(os.path.join(args.outdir, "e5_real_images.csv"), e5)
    md += ["## E5. Real photographs: agreement with OpenCV Canny", "",
           "There is no ground truth for these photographs, so this table shows how closely each method agrees with OpenCV Canny "
           "(median-rule thresholds, F1 with 2 px tolerance) and how many pixels are marked as edges. High agreement does not mean high "
           "accuracy, because OpenCV Canny is itself only an algorithm.", "",
           md_table(e5, ["image", "opencv_density_%", "improved_fixed_agree", "improved_median_agree", "improved_otsu_agree", "sobel_agree",
                         "prewitt_agree", "laplacian_agree", "improved_fixed_density_%", "improved_median_density_%", "improved_otsu_density_%"]), ""]

    # ---------------- denoiser picture on a noisy real image ----------------
    noisy = add_noise(to_gray(os.path.join(ROOT, "images", "Lenna.png"))[:256, :256], 25, 0)
    panels = {"Gaussian": canny_improved(noisy, denoise="gaussian", threshold="median").edges,
              "Median": canny_improved(noisy, denoise="median", threshold="median").edges,
              "Bilateral": canny_improved(noisy, denoise="bilateral", threshold="median").edges,
              "Non-local means": canny_improved(noisy, denoise="nlm", threshold="median").edges,
              "No denoising": canny_improved(noisy, denoise="none", threshold="median").edges}
    comparison_grid(noisy, panels, os.path.join(fig_dir, "denoise_comparison_noisy_lenna.png"), title="Lenna crop with noise (sigma 25), median thresholds", ncols=3)
    plt.close("all")

    md += ["## Metric notes", "",
           "Precision is the share of detected edge pixels near a true edge. Recall is the share of true edge pixels that were found. "
           "F1 combines them. All three use a 2 px tolerance and no one-to-one matching, and they are only available for the drawn scenes. "
           "Drawn scenes are cleaner and simpler than photographs, so scores above do not predict photo accuracy. "
           f"Run time of this script: {time.time() - t_start:.0f} s.", ""]
    with open(os.path.join(args.outdir, "summary.md"), "w") as f:
        f.write("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
